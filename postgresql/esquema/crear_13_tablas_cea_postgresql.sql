-- Taller 2 DML | Base de Datos 1
-- Ejecutar SOLO conectado a la base cea_bibliografia en pgAdmin 4.
-- Adaptacion de practica de las 13 tablas del CEA bibliografico.
-- No destruye tablas existentes. No ejecuta INSERT, UPDATE ni DELETE.

CREATE TABLE IF NOT EXISTS investigador (
 id_investigador INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(80) NOT NULL,
 apellido VARCHAR(80) NOT NULL,
 correo VARCHAR(150) UNIQUE NOT NULL
);
CREATE TABLE IF NOT EXISTS autor (
 id_investigador INTEGER PRIMARY KEY,
 CONSTRAINT fk_autor_investigador FOREIGN KEY (id_investigador)
   REFERENCES investigador(id_investigador) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE TABLE IF NOT EXISTS colaborador (
 id_investigador INTEGER PRIMARY KEY,
 CONSTRAINT fk_colaborador_investigador FOREIGN KEY (id_investigador)
   REFERENCES investigador(id_investigador) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS tema_interes (
 id_investigador INTEGER NOT NULL REFERENCES investigador(id_investigador)
   ON DELETE CASCADE ON UPDATE CASCADE,
 tema VARCHAR(150) NOT NULL,
 PRIMARY KEY (id_investigador, tema)
);
CREATE TABLE IF NOT EXISTS articulo (
 id_articulo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 titulo VARCHAR(220) NOT NULL,
 anio_publicacion INTEGER
);
CREATE TABLE IF NOT EXISTS palabra_clave (
 id_articulo INTEGER NOT NULL REFERENCES articulo(id_articulo)
   ON DELETE CASCADE ON UPDATE CASCADE,
 palabra VARCHAR(100) NOT NULL,
 PRIMARY KEY (id_articulo, palabra)
);
CREATE TABLE IF NOT EXISTS articulo_autor (
 id_articulo INTEGER NOT NULL REFERENCES articulo(id_articulo)
   ON DELETE CASCADE ON UPDATE CASCADE,
 id_investigador INTEGER NOT NULL REFERENCES autor(id_investigador)
   ON DELETE RESTRICT ON UPDATE CASCADE,
 PRIMARY KEY (id_articulo, id_investigador)
);
CREATE TABLE IF NOT EXISTS ubicacion_copia (
 id_articulo INTEGER NOT NULL REFERENCES articulo(id_articulo)
   ON DELETE CASCADE ON UPDATE CASCADE,
 lugar VARCHAR(200) NOT NULL,
 PRIMARY KEY (id_articulo, lugar)
);
CREATE TABLE IF NOT EXISTS congreso (
 id_congreso INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('NACIONAL', 'INTERNACIONAL')),
 pais VARCHAR(80),
 CONSTRAINT ck_congreso_pais CHECK (
   (tipo = 'NACIONAL' AND pais IS NULL) OR
   (tipo = 'INTERNACIONAL' AND pais IS NOT NULL)
 )
);
CREATE TABLE IF NOT EXISTS revista (
 id_revista INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(160) NOT NULL
);
CREATE TABLE IF NOT EXISTS informe_tecnico (
 id_articulo INTEGER PRIMARY KEY REFERENCES articulo(id_articulo)
   ON DELETE CASCADE ON UPDATE CASCADE,
 numero_id VARCHAR(30) NOT NULL UNIQUE,
 centro_publicacion VARCHAR(160)
);
CREATE TABLE IF NOT EXISTS acta_congreso (
 id_articulo INTEGER PRIMARY KEY REFERENCES articulo(id_articulo)
   ON DELETE CASCADE ON UPDATE CASCADE,
 id_congreso INTEGER NOT NULL REFERENCES congreso(id_congreso)
   ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE TABLE IF NOT EXISTS articulo_revista (
 id_articulo INTEGER PRIMARY KEY REFERENCES articulo(id_articulo)
   ON DELETE CASCADE ON UPDATE CASCADE,
 numero_revista INTEGER NOT NULL,
 id_revista INTEGER NOT NULL REFERENCES revista(id_revista)
   ON DELETE RESTRICT ON UPDATE CASCADE
);
SELECT table_name FROM information_schema.tables
WHERE table_schema = 'public' AND table_type = 'BASE TABLE'
ORDER BY table_name;
